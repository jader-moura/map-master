// Builds src/lib/gw2/mapWaypoints.ts: one representative waypoint per Tyria map
// (the waypoint nearest the map centre), plus a region -> map-names index.
//
// Source: https://api.guildwars2.com/v2/continents/1/floors/1 — each map's
// points_of_interest include waypoints with an accurate `chat_link`.
//
// Run: node scripts/sync-map-waypoints.mjs

import { writeFile } from "node:fs/promises";

const FLOOR = "https://api.guildwars2.com/v2/continents/1/floors/1";
const OUT = new URL("../src/lib/gw2/mapWaypoints.ts", import.meta.url);

const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);

const res = await fetch(FLOOR, { headers: { "User-Agent": "buildop sync" } });
if (!res.ok) throw new Error(`floor fetch failed: ${res.status}`);
const floor = await res.json();

/** @type {Record<string, {name:string, chat:string, coord:[number,number]}>} */
const mapWaypoints = {};
/** @type {Record<string, string[]>} */
const regionMaps = {};

for (const region of Object.values(floor.regions)) {
  const maps = [];
  for (const map of Object.values(region.maps)) {
    if (!map.name || !map.continent_rect) continue;
    const cr = map.continent_rect;
    const center = [(cr[0][0] + cr[1][0]) / 2, (cr[0][1] + cr[1][1]) / 2];
    const wps = Object.values(map.points_of_interest ?? {}).filter(
      (p) => p.type === "waypoint" && p.chat_link && Array.isArray(p.coord),
    );
    if (!wps.length) continue;
    wps.sort((a, b) => dist(a.coord, center) - dist(b.coord, center));
    const wp = wps[0];
    mapWaypoints[map.name] = {
      name: wp.name || `${map.name} Waypoint`,
      chat: wp.chat_link,
      coord: [Math.round(wp.coord[0]), Math.round(wp.coord[1])],
    };
    maps.push(map.name);
  }
  if (maps.length) regionMaps[region.name] = maps.sort();
}

const sortedWp = Object.fromEntries(Object.entries(mapWaypoints).sort(([a], [b]) => a.localeCompare(b)));
const sortedRegions = Object.fromEntries(Object.entries(regionMaps).sort(([a], [b]) => a.localeCompare(b)));

const ts = `// AUTO-GENERATED by scripts/sync-map-waypoints.mjs — do not edit by hand.
// One representative waypoint per Tyria map (nearest the map centre) with its
// in-game chat code, plus a region -> map-names index. Source: GW2 API
// /v2/continents/1/floors/1 (chat_link is provided directly by the API).

export type MapWaypoint = { name: string; chat: string; coord: [number, number] };

export const MAP_WAYPOINTS: Record<string, MapWaypoint> = ${JSON.stringify(sortedWp, null, 2)};

export const REGION_MAPS: Record<string, string[]> = ${JSON.stringify(sortedRegions, null, 2)};
`;

await writeFile(OUT, ts, "utf8");
console.log(`Wrote ${Object.keys(sortedWp).length} map waypoints across ${Object.keys(sortedRegions).length} regions.`);
console.log("Regions:", Object.keys(sortedRegions).join(", "));
