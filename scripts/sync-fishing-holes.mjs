// Builds src/lib/gw2/fishingHoles.ts: real in-game fishing-hole locations per
// fishing region, converted from the "Only Fish" marker pack to GW2 continent
// coordinates so they render on our Leaflet maps.
//
// The GW2 API has no fishing-hole coordinates, so these come from the community
// "Only Fish" marker pack (https://github.com/Metallis/Only-Fish-Marker-Pack),
// licensed CC BY-NC-SA 4.0. The generated data file inherits that license and
// credits the authors. Holes are kept only for maps that belong to one of our
// fishing regions (see src/lib/gw2/fishingMaps.ts).
//
// Marker-pack POIs store a MapID + world-space position in metres (Mumble link).
// We convert to continent coords with each map's map_rect / continent_rect from
// /v2/maps (metres -> inches, then the standard map->continent transform with a
// Y flip). Run: node scripts/sync-fishing-holes.mjs

import { readFileSync, writeFileSync } from "node:fs";

const API = "https://api.guildwars2.com/v2";
const PACK =
  "https://raw.githubusercontent.com/Metallis/Only-Fish-Marker-Pack/prod/fishing_holes.xml";
const OUT = new URL("../src/lib/gw2/fishingHoles.ts", import.meta.url);
const MAPS_TS = new URL("../src/lib/gw2/fishingMaps.ts", import.meta.url);
const UA = { "User-Agent": "buildop sync (buildop.app)" };
const METRES_TO_INCHES = 39.3701;

const round = (n) => Math.round(n);

// region slug -> [map names] taken straight from the generated fishingMaps.ts so
// hole grouping always lines up with the maps the page already renders.
function regionMapNames() {
  const src = readFileSync(MAPS_TS, "utf8");
  const marker = "FISHING_REGION_MAPS: Record<string, FishingMap[]> = ";
  const start = src.indexOf("{", src.indexOf(marker));
  const obj = JSON.parse(src.slice(start, src.lastIndexOf("}") + 1));
  const nameToRegion = new Map();
  for (const [slug, maps] of Object.entries(obj)) {
    for (const m of maps) nameToRegion.set(m.name, slug);
  }
  return nameToRegion;
}

// World metres (Mumble) -> continent coords using a map's rects.
function toContinent(meta, xMetres, zMetres) {
  const mr = meta.map_rect;
  const cr = meta.continent_rect;
  const ix = xMetres * METRES_TO_INCHES;
  const iz = zMetres * METRES_TO_INCHES;
  const cx = cr[0][0] + ((ix - mr[0][0]) / (mr[1][0] - mr[0][0])) * (cr[1][0] - cr[0][0]);
  const ty = 1 - (iz - mr[0][1]) / (mr[1][1] - mr[0][1]); // continent Y grows southward
  const cy = cr[0][1] + ty * (cr[1][1] - cr[0][1]);
  return [round(cx), round(cy)];
}

console.log("Fetching map rects + Only Fish pack…");
const [maps, xml] = await Promise.all([
  fetch(`${API}/maps?ids=all`, { headers: UA }).then((r) => r.json()),
  fetch(PACK, { headers: UA }).then((r) => r.text()),
]);

const metaById = new Map();
const idToName = new Map();
for (const m of maps) {
  if (m.continent_id === 1 && m.map_rect && m.continent_rect) {
    metaById.set(m.id, m);
    if (!idToName.has(m.id)) idToName.set(m.id, m.name);
  }
}

const nameToRegion = regionMapNames();
const attr = (s, k) => {
  const m = s.match(new RegExp(`${k}="([^"]*)"`));
  return m ? m[1] : null;
};

const out = {};
let kept = 0;
let dropped = 0;
for (const tag of xml.matchAll(/<POI\b[^>]*\/?>/g)) {
  const p = tag[0];
  const mapId = Number(attr(p, "MapID"));
  const meta = metaById.get(mapId);
  const mapName = idToName.get(mapId);
  const region = mapName ? nameToRegion.get(mapName) : undefined;
  if (!meta || !region) {
    dropped++;
    continue;
  }
  const coord = toContinent(meta, Number(attr(p, "xpos")), Number(attr(p, "zpos")));
  const type = (attr(p, "type") || "").split(".").pop() || "random";
  (out[region] ??= []).push({ map: mapName, type, coord });
  kept++;
}

const ts = `// AUTO-GENERATED by scripts/sync-fishing-holes.mjs — do not edit by hand.
//
// Real in-game fishing-hole locations per fishing region, in GW2 continent
// coordinates. Source: the "Only Fish" marker pack by Metallis with help from
// maanlichtje, LDR, Neroc, HeroineDark and HexedHero
// (https://github.com/Metallis/Only-Fish-Marker-Pack).
//
// LICENSE: This data is derived from the Only Fish marker pack and is therefore
// licensed CC BY-NC-SA 4.0 (https://creativecommons.org/licenses/by-nc-sa/4.0/).
// NonCommercial: do not use in a commercial context without the authors' consent.

export type FishingHole = {
  /** Map the hole sits on, matching a FishingMap.name. */
  map: string;
  /** Water/hole category leaf from the pack, e.g. "lake", "coastal", "desert". */
  type: string;
  /** Position in continent coordinates. */
  coord: [number, number];
};

export const FISHING_REGION_HOLES: Record<string, FishingHole[]> = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(OUT, ts, "utf8");
const regions = Object.keys(out).length;
console.log(`\nWrote ${kept} holes across ${regions} regions (dropped ${dropped} off-region/unknown maps).`);
for (const [slug, holes] of Object.entries(out).sort((a, b) => b[1].length - a[1].length)) {
  console.log(`  ${slug.padEnd(20)} ${holes.length}`);
}
