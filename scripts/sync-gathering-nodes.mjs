// Builds src/lib/gw2/gatheringNodes.ts: fixed gathering-node locations (ore, wood
// and plant spawn points) in GW2 continent coordinates, for the gathering map.
//
// Source: the "Tyrian Gathering Marker Project" by kriana
// (https://github.com/kriana/Tyrian-Gathering-Marker-Project), released into the
// public domain under CC0-1.0 — free to use, including commercially. We credit
// it anyway as a courtesy. It covers a curated set of core-Tyria maps, so node
// pins are exact where available and the map still falls back to zone highlights
// everywhere else.
//
// Marker-pack POIs store a MapID + world-space position in metres (Mumble link).
// We convert to continent coords with each map's map_rect / continent_rect from
// /v2/maps (metres -> inches, then the standard transform with a Y flip), the
// same maths as scripts/sync-fishing-holes.mjs.
// Run: node scripts/sync-gathering-nodes.mjs

import { writeFileSync } from "node:fs";

const API = "https://api.guildwars2.com/v2";
const REPO = "kriana/Tyrian-Gathering-Marker-Project";
const OUT = new URL("../src/lib/gw2/gatheringNodes.ts", import.meta.url);
const UA = { "User-Agent": "buildop sync (buildop.app)" };
const METRES_TO_INCHES = 39.3701;
const CATEGORIES = new Set(["wood", "ore", "plant"]);

const round = (n) => Math.round(n);
const json = (u) => fetch(u, { headers: UA }).then((r) => (r.ok ? r.json() : Promise.reject(new Error(`${u} -> ${r.status}`))));
const text = (u) => fetch(u, { headers: UA }).then((r) => (r.ok ? r.text() : Promise.reject(new Error(`${u} -> ${r.status}`))));
const attr = (s, k) => {
  const m = s.match(new RegExp(`${k}="([^"]*)"`));
  return m ? m[1] : null;
};

function toContinent(meta, xMetres, zMetres) {
  const mr = meta.map_rect;
  const cr = meta.continent_rect;
  const ix = xMetres * METRES_TO_INCHES;
  const iz = zMetres * METRES_TO_INCHES;
  const cx = cr[0][0] + ((ix - mr[0][0]) / (mr[1][0] - mr[0][0])) * (cr[1][0] - cr[0][0]);
  const ty = 1 - (iz - mr[0][1]) / (mr[1][1] - mr[0][1]); // continent Y grows southward
  const cy = cr[0][1] + ty * (cr[1][1] - cr[0][1]);
  return [round(cx), round(cy)];
}

console.log("Fetching map rects + TGMP file list…");
const [maps, tree] = await Promise.all([
  json(`${API}/maps?ids=all`),
  json(`https://api.github.com/repos/${REPO}/git/trees/main?recursive=1`),
]);

const metaById = new Map();
const nameById = new Map();
for (const m of maps) {
  if (m.continent_id === 1 && m.map_rect && m.continent_rect) {
    metaById.set(m.id, m);
    if (!nameById.has(m.id)) nameById.set(m.id, m.name);
  }
}

const xmlFiles = tree.tree
  .map((t) => t.path)
  .filter((p) => /^TGMP_\d+_.*\.xml$/i.test(p));

const out = [];
let dropped = 0;
for (const file of xmlFiles) {
  const xml = await text(`https://raw.githubusercontent.com/${REPO}/main/${file}`);
  for (const tag of xml.matchAll(/<POI\b[^>]*\/?>/g)) {
    const p = tag[0];
    const meta = metaById.get(Number(attr(p, "MapID")));
    const mapName = nameById.get(Number(attr(p, "MapID")));
    const parts = (attr(p, "type") || "").split(".");
    const cat = parts[1];
    if (!meta || !mapName || !CATEGORIES.has(cat)) {
      dropped++;
      continue;
    }
    const rich = parts.includes("rich");
    const kind = parts[parts.length - 1];
    const coord = toContinent(meta, Number(attr(p, "xpos")), Number(attr(p, "zpos")));
    out.push({ map: mapName, cat, kind, rich, coord });
  }
}

// Group by category for a readable, diff-friendly file.
out.sort((a, b) => a.cat.localeCompare(b.cat) || a.map.localeCompare(b.map) || a.kind.localeCompare(b.kind));

const ts = `// AUTO-GENERATED by scripts/sync-gathering-nodes.mjs — do not edit by hand.
//
// Fixed gathering-node spawn points (ore, wood, plant) in GW2 continent
// coordinates. Source: the "Tyrian Gathering Marker Project" by kriana
// (https://github.com/kriana/Tyrian-Gathering-Marker-Project), CC0-1.0 (public
// domain). Covers a curated set of core-Tyria maps; the gathering map falls back
// to zone-level highlighting where node pins aren't available.

export type GatherNode = {
  /** Map name, matching a /v2/maps name. */
  map: string;
  /** Node category: "ore" | "wood" | "plant". */
  cat: string;
  /** Node kind leaf, e.g. ore tier ("mithril"), wood tier ("elder"), plant ("onions"). */
  kind: string;
  /** Whether this is a rich node (rich veins / orchards). */
  rich: boolean;
  /** Position in continent coordinates. */
  coord: [number, number];
};

export const GATHERING_NODES: GatherNode[] = ${JSON.stringify(out)};

/** Map names that have node pins (others rely on zone highlighting). */
export const GATHERING_NODE_MAPS: string[] = ${JSON.stringify([...new Set(out.map((n) => n.map))].sort())};
`;

writeFileSync(OUT, ts, "utf8");
const byCat = {};
for (const n of out) byCat[n.cat] = (byCat[n.cat] ?? 0) + 1;
console.log(`\nWrote ${out.length} nodes across ${new Set(out.map((n) => n.map)).size} maps (dropped ${dropped}).`);
console.log("by category:", JSON.stringify(byCat));
